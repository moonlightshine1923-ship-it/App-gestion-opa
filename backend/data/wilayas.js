export function wilayaNom(code) {
  const w = WILAYAS.find((x) => x.code === code);
  return w ? w.nom : code;
}

export function wilayaNomAr(code) {
  const w = WILAYAS.find((x) => x.code === code);
  return w ? w.nomAr : code;
}

export function docTypeLibelle(code) {
  const d = DOC_TYPES.find((x) => x.code === code);
  return d ? d.libelle : code;
}

// Détermine le modèle de carte et les libellés (selon le niveau / type d'adhérent).
// - "gold"   -> modèle médaillon doré : Adhérent Gold, Membre Actif, Conseiller
// - "simple" -> modèle logo OPA : Adhérent Simple
export function carteInfo(adherent) {
  const niveau = adherent.niveau || '';
  const type = adherent.type_code || '';
  // Libellé arabe affiché en bas de carte (الصفة + bandeau)
  let modele = 'simple';
  let basAr = 'بطاقة منخرط';      // adhérent simple
  let qualiteAr = 'منخرط';

  if (niveau === 'Bureau exécutif' || type === 'BE') {
    modele = 'be'; basAr = 'بطاقة المكتب التنفيذي'; qualiteAr = adherent.bureau_badge_type || 'المكتب التنفيذي';
  } else if (niveau === 'Conseiller' || type === 'CR') {
    modele = 'gold'; basAr = 'بطاقة مستشار'; qualiteAr = 'مستشار';
  } else if (niveau === 'Membre Actif' || type === 'MA') {
    modele = 'gold'; basAr = 'بطاقة عضو فعّال'; qualiteAr = 'عضو فعّال';
  } else if (niveau === 'Adhérent Gold') {
    modele = 'gold'; basAr = 'بطاقة منخرط '; qualiteAr = 'منخرط ';
  } else {
    modele = 'simple'; basAr = 'بطاقة منخرط'; qualiteAr = 'منخرط';
  }
  // Une qualité saisie manuellement remplace le libellé automatique sur la carte.
  if (adherent.qualite_ar && String(adherent.qualite_ar).trim()) {
    qualiteAr = String(adherent.qualite_ar).trim();
  }

  return { modele, basAr, qualiteAr };
}

